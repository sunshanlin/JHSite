// loc/vo-durations.json (measure-vo.py) + loc/vo-cues.json → src/loc/vo.ts · `--beats`: loc/beats.json (gen-beats.mjs) instead, the
// no-voice timing, and NARRATED = false (Loc.tsx then plays no VO and the lo-fi BGM from the start, timeline.ts cuts on its grid).
// Word cues: each names a syllable of a line; its time comes from the line's speech runs. A pause that falls on a phrase break of
// the script (within 2 syllables of where an even pace puts it) anchors that break, and the syllables between two anchors share
// their speech time evenly. Measured on the audio, so a retake of a line moves its cues with it.
import fs from 'node:fs';
const narrated = !process.argv.includes('--beats');
const source = narrated ? 'vo-durations.json' : 'beats.json';
const meta = JSON.parse(fs.readFileSync(new URL(`./${source}`, import.meta.url), 'utf8'));
const spec = JSON.parse(fs.readFileSync(new URL('./vo-cues.json', import.meta.url), 'utf8'));

function aligner(no) {
  const m = meta[no - 1], phrases = spec.phrases[no];
  if (!phrases) throw new Error(`vo-cues.json: no phrases for line ${no}`);
  if (phrases.length !== m.text.split(' ').length) throw new Error(`vo-cues.json: line ${no} has ${m.text.split(' ').length} phrases, the spec ${phrases.length}`);
  const segs = m.segs, cum = [0];
  for (const [s, e] of segs) cum.push(cum[cum.length - 1] + e - s);
  const speech = cum[segs.length], total = phrases.reduce((a, b) => a + b, 0);
  const breaks = phrases.slice(0, -1).map((_, i) => phrases.slice(0, i + 1).reduce((a, b) => a + b, 0));
  const anchors = [[0, 0]];
  for (let k = 1; k < segs.length; k++) {
    const est = (cum[k] / speech) * total;
    const b = breaks.reduce((best, x) => (Math.abs(x - est) < Math.abs(best - est) ? x : best), -99);
    if (Math.abs(b - est) <= 2 && b > anchors[anchors.length - 1][0]) anchors.push([b, cum[k]]);
  }
  anchors.push([total, speech]);
  // speech time → file time: a phrase start lands on the start of its run, not the end of the pause before it
  const toSec = (u) => {
    let k = 0;
    while (k + 1 < segs.length && cum[k + 1] <= u) k++;
    return segs[k][0] + Math.min(u - cum[k], segs[k][1] - segs[k][0]);
  };
  const at = (syl) => {
    let i = 0;
    while (i + 2 < anchors.length && anchors[i + 1][0] <= syl) i++;
    const [s0, u0] = anchors[i], [s1, u1] = anchors[i + 1];
    return toSec(u0 + ((syl - s0) / (s1 - s0)) * (u1 - u0));
  };
  return { at, anchors: anchors.slice(1, -1).map(([b]) => b) };
}

const lines = {};
const cues = Object.entries(spec.cues).map(([name, list]) => {
  const pts = list.map(([no, syl, word]) => {
    lines[no] ??= aligner(no);
    const sec = Math.round(lines[no].at(syl) * 100) / 100;
    console.log(`${name.padEnd(13)} line ${String(no).padStart(2)} syl ${String(syl).padStart(4)}  ${sec.toFixed(2)}s  ${word}`);
    return `{ no: ${no}, sec: ${sec} }`;
  });
  return `  ${name}: [${pts.join(', ')}],`;
});
for (const [no, l] of Object.entries(lines)) console.log(`line ${no} anchored at syllables ${l.anchors.join(', ') || '(none)'}`);

const rows = meta
  .map((m) => `  { no: ${Number(m.no)}, sec: ${m.sec}, speechStart: ${m.speechStart}, speechEnd: ${m.speechEnd}, text: ${JSON.stringify(m.text)} },`)
  .join('\n');
fs.writeFileSync(
  new URL('../src/loc/vo.ts', import.meta.url),
  `// GENERATED by loc/gen-vo.mjs from loc/${source} and loc/vo-cues.json — do not edit. ${narrated ? 'Seconds are measured on the audio files.' : 'No voice: seconds are reading time (gen-beats.mjs).'}
export const NARRATED = ${narrated};
export type VoLine = { no: number; sec: number; speechStart: number; speechEnd: number; text: string };
export const VO: VoLine[] = [
${rows}
];
export const voFile = (no: number) => \`audio/vo/loc-\${String(no).padStart(2, '0')}.mp3\`;
/** word cues: line and seconds from the start of its file */
export const CUES = {
${cues.join('\n')}
};
export type CueName = keyof typeof CUES;
`,
);
console.log('src/loc/vo.ts', meta.length, 'lines,', cues.length, 'cues, from', source);
