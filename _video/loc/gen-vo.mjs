// loc/vo-durations.json (from vo-scratch.py, or re-measured after the Botnoi files land) → src/loc/vo.ts
import fs from 'node:fs';
const meta = JSON.parse(fs.readFileSync(new URL('./vo-durations.json', import.meta.url), 'utf8'));
const rows = meta
  .map((m) => `  { no: ${Number(m.no)}, sec: ${m.sec}, speechStart: ${m.speechStart}, speechEnd: ${m.speechEnd}, text: ${JSON.stringify(m.text)} },`)
  .join('\n');
fs.writeFileSync(
  new URL('../src/loc/vo.ts', import.meta.url),
  `// GENERATED by loc/gen-vo.mjs from loc/vo-durations.json — do not edit. Seconds are measured on the audio files.
export type VoLine = { no: number; sec: number; speechStart: number; speechEnd: number; text: string };
export const VO: VoLine[] = [
${rows}
];
export const voFile = (no: number) => \`audio/vo/loc-\${String(no).padStart(2, '0')}.mp3\`;
`,
);
console.log('src/loc/vo.ts', meta.length, 'lines');
